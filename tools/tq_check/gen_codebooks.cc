// Writes src/hnswtq_codebooks.h: Ginger's TurboQuant codebooks as C tables.
//
// Ginger computes several of its tables at compile time (the 4+k decision
// boundaries, and the piecewise-cubic 4+6 and 4+8 bit codebooks), so they are
// generated from its headers rather than copied by hand. Every float is
// printed with 9 significant digits, which reads back as the same float.
//
//   c++ -std=c++20 -I third_party/ginger tools/tq_check/gen_codebooks.cc -o gen_codebooks
//   ./gen_codebooks > src/hnswtq_codebooks.h
#include <cstdio>
#include <string>

#include "ginger/turboquant/codebooks/codebooks.h"

namespace tq = ginger::turboquant_codebooks;

static void PrintFloat(float v) { std::printf("%.9ef", static_cast<double>(v)); }

template <typename Row>
static void PrintRows(const char* name, int rows, int cols, const Row& get) {
  std::printf("static const float %s[%d][%d] = {\n", name, rows, cols);
  for (int r = 0; r < rows; ++r) {
    std::printf("\t{");
    for (int c = 0; c < cols; ++c) {
      if (c > 0) std::printf(",%s", c % 4 == 0 ? "\n\t " : " ");
      PrintFloat(get(r, c));
    }
    std::printf("}%s\n", r + 1 < rows ? "," : "");
  }
  std::printf("};\n\n");
}

template <int k>
static void PrintCodebook() {
  constexpr int n = 1 << k;
  const std::string centroids = "hnsw_tq_centroids_4plus" + std::to_string(k);
  const std::string boundaries = "hnsw_tq_boundaries_4plus" + std::to_string(k);
  PrintRows(centroids.c_str(), 8, n, [](int b, int s) {
    return tq::LookupCentroidPos<k>(b, static_cast<uint8_t>(s));
  });
  const auto& table = []() -> const auto& {
    if constexpr (k == 1) return tq::kBoundaries4Plus1Bit;
    else if constexpr (k == 2) return tq::kBoundaries4Plus2Bit;
    else if constexpr (k == 3) return tq::kBoundaries4Plus3Bit;
    else if constexpr (k == 4) return tq::kBoundaries4Plus4Bit;
    else if constexpr (k == 6) return tq::kBoundaries4Plus6Bit;
    else return tq::kBoundaries4Plus8Bit;
  }();
  PrintRows(boundaries.c_str(), 8, n - 1, [&](int b, int s) { return table[b][s]; });
}

int main() {
  std::printf(
      "/*\n"
      " * TurboQuant codebooks, generated by tools/tq_check/gen_codebooks.cc from\n"
      " * Ginger's ginger/turboquant/codebooks/ (third_party/ginger). Do not edit.\n"
      " *\n"
      " * Copyright 2026 Google LLC. Licensed under the Apache License, Version 2.0;\n"
      " * see http://www.apache.org/licenses/LICENSE-2.0.\n"
      " *\n"
      " * The centroids are symmetric around zero, so only magnitudes are stored: a\n"
      " * 4-bit code is (sign << 3) | bucket. The 4+k bit codebooks refine each of\n"
      " * the 8 buckets into 2^k sub-centroids; boundaries are the midpoints\n"
      " * between adjacent sub-centroids.\n"
      " */\n"
      "#ifndef HNSWTQ_CODEBOOKS_H\n"
      "#define HNSWTQ_CODEBOOKS_H\n\n");

  std::printf("/* Decision boundaries between the 8 base buckets (kBoundaries) */\n");
  std::printf("static const float hnsw_tq_boundaries[7] = {");
  for (size_t i = 0; i < tq::kBoundaries.size(); ++i) {
    std::printf("%s", i ? ", " : "");
    PrintFloat(tq::kBoundaries[i]);
  }
  std::printf("};\n\n");

  std::printf("/* Squared int8 centroids of the base buckets (kSquaredCentroids) */\n");
  std::printf("static const float hnsw_tq_squared_centroids[8] = {");
  for (size_t i = 0; i < tq::kSquaredCentroids.size(); ++i) {
    std::printf("%s", i ? ", " : "");
    PrintFloat(tq::kSquaredCentroids[i]);
  }
  std::printf("};\n\n");

  std::printf("/* Signed int8 centroids indexed by 4-bit code (kTurboQuantCentroidsInt8) */\n");
  std::printf("static const int8_t hnsw_tq_centroids_int8[16] = {");
  for (size_t i = 0; i < tq::kTurboQuantCentroidsInt8.size(); ++i)
    std::printf("%s%d", i ? ", " : "", tq::kTurboQuantCentroidsInt8[i]);
  std::printf("};\n\n");

  std::printf("/* 4+k bit codebooks: positive sub-centroids and their boundaries */\n");
  PrintCodebook<1>();
  PrintCodebook<2>();
  PrintCodebook<3>();
  PrintCodebook<4>();
  std::printf("/* 4+6 and 4+8: Ginger's piecewise-cubic fits (k*BitFitted) */\n");
  PrintCodebook<6>();
  PrintCodebook<8>();

  std::printf("#endif\t\t\t\t\t\t\t/* HNSWTQ_CODEBOOKS_H */\n");
  return 0;
}
